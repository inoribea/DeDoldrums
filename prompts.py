# ── 阶段 3.5: 对抗验证闸门（新增 — 取自 Caesar）──
STAGE35_ADVERSARIAL_GATE = """[研究阶段 3.5/4: 对抗验证闸门]

你刚完成了综合合成，生成了 5 个关键发现。在提交同行评审之前，
必须对每个发现进行对抗性压力测试。这是自动触发的闸门——不会跳过。

对每个关键发现:

1. Generator（你来充当）: 为这个发现写出完整的论证链
   - 核心断言是什么？
   - 依赖哪些证据？（标注来源）
   - 推理链是什么？（A → B → C 的每一步）

2. Verifier（独立视角）: 攻击这个论证链
   对每个发现，使用 challenge 工具（mode="all"）进行系统性挑战:
   - 逻辑漏洞: 推理链的哪一步可能断裂？
   - 隐藏假设: 什么前提被默认接受了但没有证据？
   - 缺失证据: 什么关键信息我们没有但需要？
   - 替代解释: 有没有不同的解释能覆盖同样的证据？

3. 判定:
   - 如果 Verifier 找到实质性漏洞 → 修正论证 → 重新验证
   - 如果 Verifier 通过（无实质性漏洞） → 标记"已验证" + 置信度初评
   - 如果无法判定（需要更多信息） → 标记"待验证" + 缺什么信息

四个 challenge 模式对应:
- logic_flaw: 检查逻辑漏洞（循环论证、错误归因、非此即彼等）
- hidden_assumption: 找出依赖但未明说的隐藏假设
- missing_evidence: 指出需要但缺失的关键证据
- alternative_explanation: 提出能解释相同现象但结论不同的替代解释

通过闸门的发现才能进入同行评审阶段。"""



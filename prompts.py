# ── 阶段 3.5: 对抗验证闸门（新增 — 取自 Caesar）──
STAGE35_ADVERSARIAL_GATE = """[研究阶段 3.5/4: 对抗验证闸门]

你刚完成了综合合成，生成了 5 个关键发现。在生成最终简报之前，
必须对每个发现进行对抗性压力测试。这是自动触发的闸门——不会跳过。

对每个关键发现:

1. Generator（你来充当）: 为这个发现写出完整的论证链
   - 核心断言是什么？
   - 依赖哪些证据？（标注来源）
   - 推理链是什么？（A → B → C 的每一步）

2. Verifier（独立验证角色）: 攻击这个论证链
   **不要在自己的上下文里直接自我审查。** 把每个论证链交给
   challenge 工具（mode="all"）——验证由独立的 content_review 角色执行，
   与你的上下文隔离。调用时:

   - 传 skeleton=true: 工具会把论证链剥离为逻辑骨架（断言+前提+推理链），
     验证者只看骨架不看你的原始措辞，切断措辞层锚定。隐含前提会被
     显式列出并标注为未经验证——这是共享盲区最容易藏身的地方。
   - 对可被一手来源验证的断言传 grounding=true: 工具会先检索外部来源，
     验证者必须基于检索结果判断，而不是凭共享记忆。

3. 判定（基于 challenge 工具返回的 verdict）:
   - 如果 Verifier 找到实质性漏洞 → 标记待修订，挑战结果随上下文进入最终简报
   - 如果 Verifier 通过（无实质性漏洞） → 标记"已验证"
   - 如果无法判定（需要更多信息） → 标记"待验证" + 缺什么信息

诚实边界（必须遵守）:
- 挑战通过 ≠ 独立确认。同谱系模型共享训练数据和 RLHF 目标，
  它们的一致不构成独立验证——这只是上下文层去污染后的模型判断。
- 未经过 grounding 检索接地、也未由非模型证据支持的断言，在最终简报中
  必须标注为「模型判断」，不得标注为「已验证」。

四个 challenge 模式对应:
- logic_flaw: 检查逻辑漏洞（循环论证、错误归因、非此即彼等）
- hidden_assumption: 找出依赖但未明说的隐藏假设
- missing_evidence: 指出需要但缺失的关键证据
- alternative_explanation: 提出能解释相同现象但结论不同的替代解释

通过闸门的发现将进入最终简报生成阶段。

## 文档级审计（P2/P8 — 出简报前的强制凭证）

完成对抗验证后，必须调用 document_audit 工具做文档级体检
（audit 查整体，challenge 打单点，两者互补）。audit 依据五条 rubric:

1. 每条关键论断有可定位来源（抽查 findings 的 source_url）
2. 反例被考虑（counterevidence 非空且具体）
3. 盲点声明诚实（Blind Spots 列出搜过/没试，非空话）
4. 标签正确（[已知] 都有来源；无来源的标了猜测）
5. 覆盖完整（每个 lens 都有产出，无空转方向）

audit 输出 pass/fail + 缺口清单（≤5 条）。

闸门凭证（P8）: 只有满足以下之一，才能进入最终简报:
- document_audit 返回 pass；或
- 存在显式降级记录: audit 未通过时，再次调用
  document_audit 并传 downgrade_note="具体理由"（哪个 rubric 没过、
  影响哪条结论），理由必须具体；该记录会进入 open_questions。

两者都没有时，流程不得进入最终简报——继续修补缺口或补齐审计。"""


